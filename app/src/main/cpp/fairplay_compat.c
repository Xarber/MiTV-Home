int fairplay_setup(fairplay_t *fp, const unsigned char req[16], unsigned char res[142]) {
    if (!fp || !req || !res || memcmp(req, "FPLY", 4) || req[14] > 3) return -1;
    if (req[4] == 3) return mitv_fairplay_setup_v3(fp, req, res);
    if (req[4] != 2) return -1;
    memcpy(res, mitv_reply_v2, sizeof(mitv_reply_v2));
    res[13] = req[14];
    fp->keymsglen = 0;
    logger_log(fp->logger, LOGGER_INFO, "FairPlay v2 setup accepted (mode %u)", req[14]);
    return 0;
}

int fairplay_handshake(fairplay_t *fp, const unsigned char req[164], unsigned char res[32]) {
    if (!fp || !req || !res || memcmp(req, "FPLY", 4)) return -1;
    if (req[4] == 3) return mitv_fairplay_handshake_v3(fp, req, res);
    if (req[4] != 2) return -1;
    memcpy(fp->keymsg, req, 164);
    fp->keymsglen = 164;
    memcpy(res, fp_header, 12);
    res[4] = 2;
    memcpy(res + 12, req + 144, 20);
    logger_log(fp->logger, LOGGER_INFO, "FairPlay v2 phase-two handshake completed");
    return 0;
}
